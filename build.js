/**
 * TDR build — combines the per-module files into one CSS and one JS bundle.
 *
 *   node build.js
 *
 * Edit the files in css/ and js/ as usual, then run this and commit dist/.
 * Each JS module is wrapped in its own try/catch so an error in one module
 * can't stop the modules after it from running.
 */
const fs = require('fs');
const path = require('path');

const ROOT = __dirname;
const DIST = path.join(ROOT, 'dist');

// Order matches the Squarespace header injection. Videos is loaded on its own page, not here.
const CSS = [
  'css/tdr-calendar.css',
  'css/tdr-faqs.css',
//   'css/tdr-quotes.css',
   'css/tdr-header.css',
   'css/tdr-menu.css',
//   'css/tdr-cast.css',
//   'css/tdr-creative.css',
   'css/tdr-misc.css',
];

const JS = [
  'js/tdr-calendar.js',
  'js/tdr-faqs.js',
//   'js/tdr-quotes.js',
   'js/navbar.js',      // must come before tdr-menu.js (builds the markup it wires up)
   'js/tdr-menu.js',
//   'js/tdr-cast.js',
//   'js/tdr-creative.js'
];

// Source files that are deliberately NOT in the bundles (loaded separately).
const EXCLUDED = [''];

// Warn about any source file that is neither bundled nor excluded, so a new or
// renamed file can't be silently left out of dist/.
const bundled = new Set([...CSS, ...JS, ...EXCLUDED]);
for (const dir of ['css', 'js']) {
  for (const name of fs.readdirSync(path.join(ROOT, dir))) {
    if (name.startsWith('.')) continue;
    if (!bundled.has(`${dir}/${name}`)) {
      console.warn(`WARNING: ${dir}/${name} is not in the build lists (CSS/JS/EXCLUDED), so it is not in dist/.`);
    }
  }
}

const read = file => fs.readFileSync(path.join(ROOT, file), 'utf8').trimEnd();

const banner = `/* TDR bundle — generated by build.js on ${new Date().toISOString()}. Do not edit; edit the source files instead. */\n`;

const css = banner + CSS.map(file =>
  `\n/* ==================== ${file} ==================== */\n\n${read(file)}\n`
).join('');

const js = banner + JS.map(file =>
  `\n/* ==================== ${file} ==================== */\n` +
  `try {\n${read(file)}\n} catch (error) {\n  console.error('[TDR] ${file} failed:', error);\n}\n`
).join('');

// Fail the build on a JS syntax error rather than shipping a broken bundle.
new Function(js);

fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(path.join(DIST, 'tdr.css'), css);
fs.writeFileSync(path.join(DIST, 'tdr.js'), js);

console.log(`dist/tdr.css  ${CSS.length} files, ${(css.length / 1024).toFixed(1)} KB`);
console.log(`dist/tdr.js   ${JS.length} files, ${(js.length / 1024).toFixed(1)} KB`);
